@router.get("/{staff_id}", response_model=dict)
async def get_staff(
    staff_id: str,
    current_user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session)
):
    """Get staff details"""
    result = await session.execute(select(Staff).where(Staff.id == staff_id))
    staff = result.scalar_one_or_none()
    
    if not staff:
        raise HTTPException(status_code=404, detail="Staff not found")
    
    if current_user.role != UserRole.SUPER_ADMIN and current_user.school_id != staff.school_id:
        raise HTTPException(status_code=403, detail="Access denied")
    assert_campus_access(current_user, staff.campus_id)

    assignments = []
    if staff.staff_type == StaffType.TEACHING:
        assign_result = await session.execute(
            select(TeacherAssignment).where(TeacherAssignment.staff_id == staff.id)
        )
        for a in assign_result.scalars().all():
            class_result = await session.execute(select(Class).where(Class.id == a.class_id))
            cls = class_result.scalar_one_or_none()
            
            subject_result = await session.execute(select(Subject).where(Subject.id == a.subject_id))
            subject = subject_result.scalar_one_or_none()
            
            assignments.append({
                "id": a.id,
                "class_id": a.class_id,
                "class_name": cls.name if cls else "Unknown",
                "subject_id": a.subject_id,
                "subject_name": subject.name if subject else "Unknown",
                "is_class_teacher": a.is_class_teacher
            })
    
    # Portal login credentials are only shown to admins managing accounts, or
    # to the staff member viewing their own record — not to every same-school
    # user this endpoint is otherwise open to (e.g. a TEACHER looking up a
    # colleague), who would otherwise walk away with that colleague's
    # plaintext password.
    portal_account = None
    if staff.user_id:
        can_see_credentials = (
            current_user.role in (UserRole.SUPER_ADMIN, UserRole.SCHOOL_ADMIN)
            or current_user.id == staff.user_id
        )
        if can_see_credentials:
            user_result = await session.execute(select(User).where(User.id == staff.user_id))
            user = user_result.scalar_one_or_none()
            if user:
                portal_account = {
                    "email": user.email,
                    "password": decrypt_onboarding_password(user.plain_text_password)
                }

    manager_name = None
    if staff.manager_id:
        manager_result = await session.execute(select(Staff).where(Staff.id == staff.manager_id))
        manager = manager_result.scalar_one_or_none()
        if manager:
            manager_name = f"{manager.first_name} {manager.last_name}"

    return {
        "id": staff.id,
        "school_id": staff.school_id,
        "staff_id": staff.staff_id,
        "first_name": staff.first_name,
        "last_name": staff.last_name,
        "full_name": f"{staff.first_name} {staff.last_name}",
        "email": staff.email,
        "phone": staff.phone,
        "date_of_birth": staff.date_of_birth,
        "gender": staff.gender,
        "staff_type": staff.staff_type,
        "position": staff.position,
        "department": staff.department,
        "manager_id": staff.manager_id,
        "manager_name": manager_name,
        "qualification": staff.qualification,
        "date_joined": staff.date_joined,
        "status": staff.status,
        "role": staff.role.value if staff.role else UserRole.TEACHER.value,
        "photo_url": staff.photo_url,
        "portal_account": portal_account,
        "assignments": assignments,
        "probation_status": staff.probation_status,
        "probation_end_date": staff.probation_end_date,
        "probation_confirmed_at": staff.probation_confirmed_at.isoformat() if staff.probation_confirmed_at else None,
        "probation_confirmed_by": staff.probation_confirmed_by,
        "created_at": staff.created_at.isoformat()
    }


