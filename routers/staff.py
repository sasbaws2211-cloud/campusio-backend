async def ensure_single_class_teacher(
    session: AsyncSession,
    class_id: str,
    academic_term_id: str,
    exclude_assignment_id: Optional[str] = None,
) -> None:
    """A class should have at most one 'class teacher' per term — that flag is used
    elsewhere (report cards, attendance responsibility) as if it identifies a single
    person. Reject a second one instead of silently allowing two."""
    query = select(TeacherAssignment).where(
        TeacherAssignment.class_id == class_id,
        TeacherAssignment.academic_term_id == academic_term_id,
        TeacherAssignment.is_class_teacher == True,
    )
    if exclude_assignment_id:
        query = query.where(TeacherAssignment.id != exclude_assignment_id)
    result = await session.execute(query)
    # .first() rather than scalar_one_or_none() — existing data can already have
    # more than one class teacher for a class/term (the exact gap this guards
    # against), so a strict one-or-none read would itself raise.
    if result.scalars().first():
        raise HTTPException(
            status_code=400,
            detail="This class already has a class teacher for this term — remove that assignment's class-teacher flag first"
        )


