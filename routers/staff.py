# Where money for staff-initiated paid activities (currently: extra classes)
# is sent. Staff submits their own bank/MoMo details; an admin verifies once,
# which creates a real Paystack subaccount — after that, payments route
# straight to the staff member with no manual payout step on the school's
# side at all.

