async def _validate_manager_id(session: AsyncSession, school_id: str, manager_id: Optional[str], staff_id: Optional[str] = None) -> None:
    """manager_id was previously accepted and stored with zero validation —
    not checked for same-school membership, not checked against
    manager_id == staff_id (self-management), and not checked for a cycle
    up the chain. A self-referencing manager_id directly enables the
    self-approval bypass fixed in routers/leave_requests.py::
    approve_leave_request (manager_approve_leave_request trusts
    requester.manager_id == manager_staff.id at face value), and a cycle
    would corrupt get_org_chart with an infinite loop. staff_id is the
    record being created/updated — None for create_staff, since a not-yet-
    inserted row can't be its own manager or appear in a cycle anyway."""
    if not manager_id:
        return
    if staff_id and manager_id == staff_id:
        raise HTTPException(status_code=422, detail="A staff member cannot be their own manager")

    result = await session.execute(select(Staff).where(Staff.id == manager_id, Staff.school_id == school_id))
    manager = result.scalar_one_or_none()
    if not manager:
        raise HTTPException(status_code=404, detail="manager_id does not exist for this school")

    if staff_id:
        # Walk up the chain from the proposed manager; if it ever reaches
        # staff_id, assigning this manager would create a cycle. Bounded
        # hop count as a defensive backstop against a pre-existing cycle
        # this check didn't catch before it existed.
        seen = set()
        current = manager
        for _ in range(50):
            if current.id == staff_id:
                raise HTTPException(status_code=422, detail="This manager assignment would create a management cycle")
            if not current.manager_id or current.id in seen:
                break
            seen.add(current.id)
            next_result = await session.execute(select(Staff).where(Staff.id == current.manager_id, Staff.school_id == school_id))
            current = next_result.scalar_one_or_none()
            if not current:
                break


async def _get_own_staff_record(current_user: User, session: AsyncSession) -> Staff:
    result = await session.execute(select(Staff).where(Staff.user_id == current_user.id))
    staff = result.scalar_one_or_none()
    if not staff and current_user.school_id:
        result = await session.execute(
            select(Staff).where(Staff.email == current_user.email, Staff.school_id == current_user.school_id)
        )
        staff = result.scalar_one_or_none()
    if not staff:
        raise HTTPException(status_code=404, detail="Staff profile not found. Please ensure your portal credentials have been generated by the admin.")
    return staff


