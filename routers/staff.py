@router.put("/my-payout-details", response_model=dict)
async def submit_my_payout_details(
    payload: dict,
    current_user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session),
):
    account_type = payload.get("account_type")
    bank_code = payload.get("bank_code")
    account_number = payload.get("account_number")
    if account_type not in ("bank", "mobile_money") or not bank_code or not account_number:
        raise HTTPException(status_code=400, detail="account_type (bank/mobile_money), bank_code, and account_number are required")

    staff = await _get_own_staff_record(current_user, session)

    paystack_secret_key = os.getenv("PAYSTACK_SECRET_KEY", "")
    if not paystack_secret_key:
        raise HTTPException(status_code=503, detail="Payment gateway not configured")

    # This is the actual anti-fraud check — Paystack confirms who really
    # owns this account before we ever store it or show it to an admin to
    # "verify". A typo'd or made-up number fails here, not after.
    paystack = PaystackService(paystack_secret_key)
    resolved = await paystack.resolve_account_number(account_number=account_number, bank_code=bank_code)
    if not resolved.get("success"):
        raise HTTPException(status_code=400, detail=resolved.get("error", "Could not verify this account number"))

    staff.payout_account_type = account_type
    staff.payout_bank_code = bank_code
    staff.payout_account_number = account_number
    staff.payout_account_name = resolved["account_name"]
    staff.payout_verification_status = PayoutVerificationStatus.PENDING
    staff.payout_submitted_at = datetime.utcnow()
    staff.payout_rejection_reason = None
    staff.paystack_subaccount_code = None  # re-submitting invalidates any prior subaccount
    staff.updated_at = datetime.utcnow()
    session.add(staff)
    await session.commit()
    await session.refresh(staff)
    return _serialize_payout_details(staff)


